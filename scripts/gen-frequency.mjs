// 词频表生成器（可复现）：从公开真实语料生成 src/review/data/frequency-full.ts
// 用法：node scripts/gen-frequency.mjs [源txt路径] [截取行数]
// 源格式：每行 "word<TAB>count"，按词频降序。rank = 1-based 行号。
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const outDir = resolve(here, "../src/review/data");
const src = process.argv[2] || "/tmp/en_freq.txt";
const limit = Number(process.argv[3] || 50000);

const raw = readFileSync(src, "utf8")
  .split(/\r?\n/)
  .map((l) => l.split(/\s+/)[0].toLowerCase().trim())
  .filter((w) => /^[a-z][a-z'’-]*$/.test(w))
  .slice(0, limit);

const body = raw.join(" ");
const header = [
  "// AUTO-GENERATED by scripts/gen-frequency.mjs — DO NOT EDIT BY HAND.",
  "// 来源：hermitdave/FrequencyWords (en_50k, word<TAB>count, 词频降序)",
  `// 词条数：${raw.length}。rank = 1-based 在 FREQUENCY_FULL_RANKED 中的位置。`,
  "// 重新生成：node scripts/gen-frequency.mjs /tmp/en_freq.txt 50000",
  "",
].join("\n");

const ts =
  header +
  `export const FREQUENCY_FULL_COUNT = ${raw.length};\n` +
  `export const FREQUENCY_FULL_RANKED: string =\n  ${JSON.stringify(body)};\n`;

writeFileSync(resolve(outDir, "frequency-full.ts"), ts);
console.log(`wrote ${raw.length} words, ${ts.length} bytes -> src/review/data/frequency-full.ts`);
